"""
make_tables.py
===============
Collects the paper tables from runs/*/eval_<year>_<tag>/metrics.json and runs/*/logscore_*.json into
one markdown file (stdlib only, Python 3.6; reads small JSON files -- fine anywhere).
Missing entries print as "--" so the file can be regenerated as jobs finish.

  python make_tables.py            # -> ../paper_tables.md
"""
import json
import os
from paths import CDFFM_ROOT  # noqa: E402  (set CDFFM_ROOT)

ROOT = CDFFM_ROOT
RUNS = f"{ROOT}/runs"
T3 = ["TG", "TX", "TN"]
SEASONS = ["DJF", "MAM", "JJA", "SON"]

FINAL = "w2e_static_pl24_l8"
MAIN = [  # (label, run, eval tag, params)
    ("CD-FFM (final)", FINAL, "final", "3.2M"),
    ("FNO FFM", "w3_fno_final", "final", "124M"),
    ("FNO FFM (size-matched)", "w3_fno16_final", "final", "7.7M"),
    ("Regression (MSE)", "w3_reg_static", "final", "3.2M"),
    ("CD-FFM, zero-noise ODE (deterministic)", FINAL, "final_det0", "3.2M"),
    ("CorrDiff-style UNet regression", "w6_unet_reg", "final_patch", "24.8M"),
    ("CorrDiff-style diffusion (every 7th day, 8 members)", "w6_corrdiff", "s7_patch", "24.8M"),
    ("CD-FFM, same 53 days, 8 members (for the row above)", FINAL, "s7_ref", "3.2M"),
    ("BCSD-style baseline", "baseline_bcsd", "best", "0"),
]
NOISE = [
    ("i.i.d.", "w3_iid_static", "final"),
    ("RBF (0.5 deg, 64 features)", "w2d_static_rbf", "final"),
    ("power law 2-500 km", "w2d_static_pl24", "final"),
    ("power law 8-500 km (final)", FINAL, "final"),
    ("power law 20-500 km", "w2e_static_pl24_l20", "final"),
]
INFER = [
    ("10 Euler steps, no constraint (reference)", FINAL, "s7_ref"),
    ("exact ERA5 cell-mean constraint", FINAL, "s7_exact"),
    ("exact constraint, monthly-debiased", FINAL, "s7_debiased"),
    ("5 Euler steps", FINAL, "s7_ode5"),
    ("20 Euler steps", FINAL, "s7_ode20"),
    ("flow map, 1 step", "w5_flowmap", "s7_map1"),
    ("flow map, 2 steps", "w5_flowmap", "s7_map2"),
    ("flow map, 4 steps", "w5_flowmap", "s7_map4"),
    ("2 Euler steps (teacher)", FINAL, "s7_ode2"),
]
PRECIP = [
    ("CD-FFM (final config)", "w4_rr_final", "final"),
    ("Regression (MSE)", "w4_rr_reg", "final"),
    ("ERA5 total precipitation, bilinear", "baseline_era5_rr", "best"),
    ("CD-FFM, zero-noise ODE", "w4_rr_final", "final_det0"),
]


def load(run, tag, year=2019):
    p = f"{RUNS}/{run}/eval_{year}_{tag}/metrics.json"
    return json.load(open(p)) if os.path.exists(p) else None


def logscore(run, tag="s7_rk20", year=2019):
    p = f"{RUNS}/{run}/logscore_{year}_{tag}.json"
    return json.load(open(p)) if os.path.exists(p) else None


def f(x, nd=3):
    return "--" if x is None else f"{x:.{nd}f}"


def crps(y):
    return y.get("crps_fair", y["crps"])


def trip(m, key, group="all", season="year", nd=3, vars_=T3):
    if m is None:
        return " / ".join("--" for _ in vars_)
    y = m["groups"][group][season]
    vals = []
    for v in vars_:
        vals.append(crps(y[v]) if key == "crps" else y[v][key])
    return " / ".join(f(x, nd) for x in vals)


def main():
    out = ["# Paper tables (auto-generated by scripts/make_tables.py)", "",
           "2019 test year, all 1.33M pixels; best validation checkpoint (2017). CRPS = fair ensemble CRPS "
           "(deterministic: MAE). Log score: exact predictive density, nats/pixel, joint TG/TX/TN (every 7th day).", ""]

    out += ["## Table 1 - temperature, main comparison", "",
            "| Model | Params | Members | CRPS TG / TX / TN | RMSE TG / TX / TN | spread/skill TG / TX / TN | "
            "Brier hot TG / TX / TN | Brier cold TG / TX / TN | log score |",
            "|---|---|---|---|---|---|---|---|---|"]
    for lab, run, tag, par in MAIN:
        m = load(run, tag)
        ls = logscore(run) if tag == "final" else None
        out.append(f"| {lab} | {par} | {m['members'] if m else '--'} | {trip(m, 'crps')} | {trip(m, 'rmse_ensmean', nd=2)} | "
                   f"{trip(m, 'spread_skill', nd=2) if m and m['members'] > 1 else '--'} | {trip(m, 'hot_brier', nd=4)} | "
                   f"{trip(m, 'cold_brier', nd=4)} | {f(ls['groups']['all']['year']['nll_degC']) if ls else '--'} |")

    out += ["", "## Table 2 - noise prior (same setup, only the noise differs)", "",
            "| Noise | CRPS TG / TX / TN | spread/skill TG | log score |", "|---|---|---|---|"]
    for lab, run, tag in NOISE:
        m, ls = load(run, tag), logscore(run)
        out.append(f"| {lab} | {trip(m, 'crps')} | {f(m['groups']['all']['year']['TG']['spread_skill'], 2) if m else '--'} | "
                   f"{f(ls['groups']['all']['year']['nll_degC']) if ls else '--'} |")

    out += ["", "## Table 3 - Lapland hold-out (CRPS TG / TX / TN)", "",
            "| Model | held-out region | rest of domain | log score held-out / rest |", "|---|---|---|---|"]
    for lab, run in [("trained on all pixels", FINAL), ("Lapland never sampled", "w3_final_lapland")]:
        m, ls = load(run, "final"), logscore(run)
        lsg = (f"{f(ls['groups']['holdout']['year']['nll_degC'])} / {f(ls['groups']['inside']['year']['nll_degC'])}"
               if ls and "holdout" in ls["groups"] else "--")
        out.append(f"| {lab} | {trip(m, 'crps', 'holdout') if m and 'holdout' in m['groups'] else '--'} | "
                   f"{trip(m, 'crps', 'inside') if m and 'inside' in m['groups'] else '--'} | {lsg} |")

    out += ["", "## Table 4 - inference-time studies (every 7th day, 8 members)", "",
            "| Setting | CRPS TG / TX / TN | spread/skill TG | TG cell mean - truth | TG cell mean - ERA5 |",
            "|---|---|---|---|---|"]
    for lab, run, tag in INFER:
        m = load(run, tag)
        r = (m or {}).get("tg_cell_mean_abs_residual_degC") or {}
        out.append(f"| {lab} | {trip(m, 'crps')} | {f(m['groups']['all']['year']['TG']['spread_skill'], 2) if m else '--'} | "
                   f"{f(r.get('pred_vs_truth'), 2)} | {f(r.get('pred_raw'), 2)} |")

    out += ["", "## Table 5 - precipitation (mm/day)", "",
            "| Model | CRPS | RMSE | bias | spread/skill | wet day freq. bias / Brier | >1 mm | >10 mm | >20 mm |",
            "|---|---|---|---|---|---|---|---|---|"]
    for lab, run, tag in PRECIP:
        m = load(run, tag)
        if m is None:
            out.append(f"| {lab} | " + " | ".join("--" for _ in range(8)) + " |")
            continue
        y = m["groups"]["all"]["year"]["RR"]
        thr = lambda t: f"{f(y[f'>{t}mm']['freq_bias'], 2)} / {f(y[f'>{t}mm']['brier'], 4)}"
        out.append(f"| {lab} | {f(crps(y))} | {f(y['rmse_ensmean'], 2)} | {f(y['bias'], 2)} | "
                   f"{f(y['spread_skill'], 2) if m['members'] > 1 else '--'} | {thr(0.1)} | {thr(1.0)} | {thr(10.0)} | {thr(20.0)} |")
    out.append("")
    out.append("Threshold columns: frequency bias / Brier score of the ensemble probability.")

    out += ["", "## Table 6 - final model by season (CRPS TG / TX / TN)", "", "| Season | CD-FFM | regression | FNO 124M |",
            "|---|---|---|---|"]
    mf, mr, mn = load(FINAL, "final"), load("w3_reg_static", "final"), load("w3_fno_final", "final")
    for s in SEASONS:
        out.append(f"| {s} | {trip(mf, 'crps', season=s)} | {trip(mr, 'crps', season=s)} | {trip(mn, 'crps', season=s)} |")

    path = f"{ROOT}/paper_tables.md"
    open(path, "w").write("\n".join(out) + "\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
