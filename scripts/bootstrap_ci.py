"""
bootstrap_ci.py
================
Paired confidence intervals for "model A vs model B" from the per-day domain means that fast_eval.py
stores in metrics.json ("daily"). For each variable: daily difference d_t = score_A(t) - score_B(t)
on the common days, moving-block bootstrap over days (block 7 days, respects day-to-day correlation),
95 % interval of the mean difference, relative difference, fraction of days A is better. Years are
pooled with blocks drawn within each year. numpy only (system python3 is fine; JSON inputs are small).

  python bootstrap_ci.py            # default comparisons -> ../paper_ci.md
"""
import json
import os

import numpy as np
from paths import CDFFM_ROOT  # noqa: E402  (set CDFFM_ROOT)

ROOT = CDFFM_ROOT
RUNS = f"{ROOT}/runs"
FINAL = "w2e_static_pl24_l8"
YEARS = [2016, 2018, 2019]
# (label, (run_A, tag_A), (run_B, tag_B)) -- negative difference = A better (lower score)
PAIRS = [
    ("flow map (2 steps) vs regression", ("w5_flowmap", "final_map2"), ("w3_reg_static", "final")),
    ("flow map (2 steps) vs FNO FFM 124M", ("w5_flowmap", "final_map2"), ("w3_fno_final", "final")),
    ("flow map (2 steps) vs BCSD", ("w5_flowmap", "final_map2"), ("baseline_bcsd", "final")),
    ("flow map (2 steps) vs Euler 10 steps", ("w5_flowmap", "final_map2"), (FINAL, "final")),
    ("FFM Euler 10 vs regression", (FINAL, "final"), ("w3_reg_static", "final")),
    ("FFM Euler 10 vs FNO FFM 124M", (FINAL, "final"), ("w3_fno_final", "final")),
    ("static descriptors: with vs without (power law 2-500 km)", ("w2d_static_pl24", "final"), ("w2b_pl24", "final")),
    ("FFM flow map (2 steps) vs CorrDiff-style (every 7th day of 2019, 8 members)", ("w5_flowmap", "s7_map2_daily"), ("w6_corrdiff", "s7_patch")),
    ("FFM Euler 10 vs CorrDiff-style (every 7th day of 2019, 8 members)", (FINAL, "s7_ref_daily"), ("w6_corrdiff", "s7_patch")),
    ("FFM zero-noise map vs CorrDiff-style UNet regression", (FINAL, "final_det0"), ("w6_unet_reg", "final_patch")),
]
METRICS = [("crps_fair", "CRPS"), ("ae_ensmean", "MAE of ens. mean")]


def daily(run, tag, year):
    p = f"{RUNS}/{run}/eval_{year}_{tag}/metrics.json"
    if not os.path.exists(p):
        return None
    m = json.load(open(p))
    if "daily" not in m:
        return None
    return m["args"].get("target", "temp"), {d["date"]: d for d in m["daily"]}


def block_bootstrap(d_by_year, n_boot=4000, block=7, seed=0):
    rng = np.random.default_rng(seed)
    means = np.empty(n_boot)
    for b in range(n_boot):
        parts = []
        for d in d_by_year:
            n = len(d)
            k = int(np.ceil(n / block))
            starts = rng.integers(0, max(n - block + 1, 1), size=k)
            idx = np.concatenate([np.arange(s, min(s + block, n)) for s in starts])[:n]
            parts.append(d[idx])
        means[b] = np.concatenate(parts).mean()
    return np.percentile(means, [2.5, 97.5])


def main():
    out = ["# Paired bootstrap confidence intervals (auto-generated by scripts/bootstrap_ci.py)", "",
           "Daily domain means, paired on common days; moving-block bootstrap (7-day blocks, within years), "
           "95 % interval of the mean difference A - B (negative = A better). Years: as available among "
           + ", ".join(map(str, YEARS)) + ".", ""]
    for label, (ra, ta), (rb, tb) in PAIRS:
        rows = []
        for key, mname in METRICS:
            for c in range(3):
                d_by_year, a_all, b_all, yrs, var = [], [], [], [], None
                for y in YEARS:
                    A, B = daily(ra, ta, y), daily(rb, tb, y)
                    if A is None or B is None:
                        continue
                    var = ["TG", "TX", "TN"] if A[0] == "temp" else ["RR"]
                    if c >= len(var):
                        continue
                    dates = sorted(set(A[1]) & set(B[1]))
                    if not dates:
                        continue
                    a = np.array([A[1][t][key][c] for t in dates])
                    b = np.array([B[1][t][key][c] for t in dates])
                    d_by_year.append(a - b)
                    a_all.append(a)
                    b_all.append(b)
                    yrs.append(f"{y}({len(dates)}d)")
                if not d_by_year:
                    continue
                a, b, d = np.concatenate(a_all), np.concatenate(b_all), np.concatenate(d_by_year)
                lo, hi = block_bootstrap(d_by_year)
                rows.append(f"| {mname} | {var[c]} | {a.mean():.3f} | {b.mean():.3f} | {d.mean():+.3f} "
                            f"[{lo:+.3f}, {hi:+.3f}] | {100 * d.mean() / b.mean():+.1f} % | {100 * (d < 0).mean():.0f} % | "
                            f"{' '.join(yrs)} |")
        out += [f"## {label}", ""]
        if rows:
            out += ["| metric | var | A | B | A - B [95 % CI] | relative | days A better | years |",
                    "|---|---|---|---|---|---|---|---|"] + rows
        else:
            out.append("(no per-day data yet)")
        out.append("")
    path = f"{ROOT}/paper_ci.md"
    open(path, "w").write("\n".join(out) + "\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
